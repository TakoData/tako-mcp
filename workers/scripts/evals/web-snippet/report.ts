#!/usr/bin/env tsx
/**
 * raw-*.jsonl (+ judged-*.jsonl if present) → RESULTS.md
 *
 * Leads with RUN HEALTH, because a run with failed calls or an empty arm that
 * gets read as a result is worse than no run. Then the two decision-relevant
 * blocks:
 *
 *   LATENCY — the thing that actually gates tako_answer. The grounding web
 *   budget is a hard 1.5s and a breach drops web grounding entirely rather
 *   than returning it late, so the tail matters more than the median. Reported
 *   as median AND max per arm, plus the paired per-case delta (the same query
 *   in both arms), which is the only comparison that cancels query difficulty.
 *
 *   COVERAGE — null-snippet rate and cap-binding rate. The upstream PR
 *   measured 0 nulls across ~40 results and no fallback to text was added on
 *   that basis; this is the number that would falsify it.
 *
 * Judged sections are omitted rather than faked when judge.ts has not run.
 *
 * Usage: npx tsx scripts/evals/web-snippet/report.ts [raw-*.jsonl]
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

import { judgedPathFor, positionalArg, resolveRaw } from "./paths.js";
import type { Arm, CallRow, CaseRow } from "./run.js";
import type { JudgedCase } from "./judge.js";

const HERE = dirname(new URL(import.meta.url).pathname);
const RESULTS = join(HERE, "results");
const ARMS: Arm[] = ["text", "highlights"];

const median = (xs: number[]): number => {
  if (xs.length === 0) return NaN;
  const s = [...xs].sort((a, b) => a - b);
  const m = Math.floor(s.length / 2);
  return s.length % 2 === 1 ? (s[m] as number) : (((s[m - 1] as number) + (s[m] as number)) / 2);
};
const mean = (xs: number[]): number =>
  xs.length === 0 ? NaN : xs.reduce((a, b) => a + b, 0) / xs.length;
const n = (x: number, d = 0): string => (Number.isNaN(x) ? "—" : x.toFixed(d));

/** The argument is the RAW sweep, not the judged file — report.ts derives the
 *  judged path itself. Checked because passing `judged-*.jsonl` otherwise dies
 *  deep in `calls()` with a bare "cannot read properties of undefined". */
function assertRawShape(rows: CaseRow[], path: string): void {
  const bad = rows.findIndex((r) => r.search === undefined || r.answer === undefined);
  if (bad === -1) return;
  console.error(
    `✘ ${path.split("/").pop()} is not a raw sweep (row ${bad + 1} has no search/answer arms).\n` +
      `  Pass the raw-*.jsonl; the judged file is picked up automatically.`,
  );
  process.exit(1);
}

function calls(rows: CaseRow[], kind: "search" | "answer", arm: Arm): CallRow[] {
  return rows.map((r) => r[kind][arm]).filter((c): c is CallRow => c !== undefined);
}

function main(): void {
  const rawPath = positionalArg(process.argv, []) ?? resolveRaw(RESULTS, "report on", "report.ts");
  const rows = readFileSync(rawPath, "utf8")
    .split("\n")
    .filter((l) => l.trim() !== "")
    .map((l) => JSON.parse(l) as CaseRow);
  assertRawShape(rows, rawPath);

  const judgedPath = judgedPathFor(rawPath);
  const judged: JudgedCase[] = existsSync(judgedPath)
    ? readFileSync(judgedPath, "utf8")
        .split("\n")
        .filter((l) => l.trim() !== "")
        .map((l) => JSON.parse(l) as JudgedCase)
    : [];

  const md: string[] = [];
  md.push("# Exa highlights vs page text — web snippet A/B");
  md.push("");
  md.push("GENERATED by `scripts/evals/web-snippet/report.ts`. Measurement, not a gate.");
  md.push("");
  md.push(`Source: \`${rawPath.split("/").pop()}\`${judged.length > 0 ? " + judged" : " (unjudged)"}`);
  md.push(`Cases: ${rows.length} · snippet_max_chars: ${rows[0]?.snippet_max_chars ?? "?"}`);
  md.push("");

  // ── Run health ───────────────────────────────────────────────────────────
  md.push("## Run health");
  md.push("");
  md.push("Read this before anything else. A failed or rate-limited arm reaches the");
  md.push("caller as an empty result set, not as an error — so a broken run looks like");
  md.push("a coverage finding unless the failures are counted here first.");
  md.push("");
  md.push("| endpoint | arm | calls | non-200 | zero-result | median results |");
  md.push("|---|---|---:|---:|---:|---:|");
  for (const kind of ["search", "answer"] as const) {
    for (const arm of ARMS) {
      const cs = calls(rows, kind, arm);
      if (cs.length === 0) continue;
      md.push(
        `| ${kind} | ${arm} | ${cs.length} | ${cs.filter((c) => c.status !== 200).length} | ` +
          `${cs.filter((c) => c.status === 200 && c.results.length === 0).length} | ` +
          `${n(median(cs.map((c) => c.results.length)), 1)} |`,
      );
    }
  }
  md.push("");
  const errs = [...(["search", "answer"] as const)].flatMap((k) =>
    ARMS.flatMap((a) => calls(rows, k, a).filter((c) => c.status !== 200).map((c) => `${k}/${a}: ${c.status} ${c.error ?? ""}`)),
  );
  if (errs.length > 0) {
    md.push("**Failures:**");
    md.push("");
    for (const e of [...new Set(errs)].slice(0, 10)) md.push(`- \`${e}\``);
    md.push("");
  }

  // ── Latency ──────────────────────────────────────────────────────────────
  md.push("## Latency — the gate on tako_answer");
  md.push("");
  md.push("Exa selects highlights with an LLM, so they cost time even though they cost");
  md.push("no money. `GROUNDING_WEB_RETRIEVAL_TIMEOUT_S` is 1.5s and a breach does not");
  md.push("return a slow answer — it returns no web grounding at all. So the max column");
  md.push("decides this, not the median.");
  md.push("");
  md.push("Arm order is rotated per case, so neither arm systematically eats the cold cache.");
  md.push("");
  md.push("| endpoint | arm | median ms | max ms | n |");
  md.push("|---|---|---:|---:|---:|");
  for (const kind of ["search", "answer"] as const) {
    for (const arm of ARMS) {
      const ms = calls(rows, kind, arm).filter((c) => c.status === 200).map((c) => c.ms);
      if (ms.length === 0) continue;
      md.push(`| ${kind} | ${arm} | ${n(median(ms))} | ${n(Math.max(...ms))} | ${ms.length} |`);
    }
  }
  md.push("");
  md.push("**Web-grounding survival on /v1/answer** — the actual degradation mode. A");
  md.push("breach of the 1.5s retrieval budget does not return a slow answer; it returns");
  md.push("an answer with no web grounding at all. So a 200 with an empty `web_results`");
  md.push("on a web-only request is the failure this table counts, and it is a stronger");
  md.push("signal than wall-clock latency (which also includes arbiter synthesis).");
  md.push("");
  md.push("| arm | answer calls | zero web results | rate |");
  md.push("|---|---:|---:|---:|");
  for (const arm of ARMS) {
    const cs = calls(rows, "answer", arm).filter((c) => c.status === 200);
    if (cs.length === 0) continue;
    const zero = cs.filter((c) => c.results.length === 0).length;
    md.push(`| ${arm} | ${cs.length} | ${zero} | ${((zero / cs.length) * 100).toFixed(0)}% |`);
  }
  md.push("");
  md.push("**Paired per-case delta** (highlights − text on the same query — the only");
  md.push("comparison that cancels query difficulty):");
  md.push("");
  md.push("| endpoint | median Δms | max Δms | slower on |");
  md.push("|---|---:|---:|---|");
  for (const kind of ["search", "answer"] as const) {
    const deltas = rows
      .map((r) => {
        const t = r[kind].text;
        const h = r[kind].highlights;
        return t?.status === 200 && h?.status === 200 ? h.ms - t.ms : null;
      })
      .filter((d): d is number => d !== null);
    if (deltas.length === 0) continue;
    md.push(
      `| ${kind} | ${n(median(deltas))} | ${n(Math.max(...deltas))} | ` +
        `${deltas.filter((d) => d > 0).length}/${deltas.length} cases |`,
    );
  }
  md.push("");

  // ── Coverage ─────────────────────────────────────────────────────────────
  md.push("## Coverage — null snippets and cap binding");
  md.push("");
  md.push("With highlights on, Tako requests no page text, so a page with no relevant");
  md.push("passage returns `snippet: null` and keeps its slot. No text fallback was");
  md.push("added upstream, on the basis of 0 nulls across ~40 results. This is the");
  md.push("number that would overturn that.");
  md.push("");
  md.push("| arm | results | null snippets | at cap | median chars | mean chars | multi-passage |");
  md.push("|---|---:|---:|---:|---:|---:|---:|");
  const cap = rows[0]?.snippet_max_chars ?? 2000;
  for (const arm of ARMS) {
    const res = calls(rows, "search", arm).flatMap((c) => c.results);
    if (res.length === 0) continue;
    const lens = res.filter((r) => r.snippet !== null).map((r) => (r.snippet as string).length);
    md.push(
      `| ${arm} | ${res.length} | ${res.filter((r) => r.snippet === null).length} | ` +
        // Within 1% of the cap: server-side enforcement lands a few chars short.
        `${lens.filter((l) => l >= cap * 0.99).length} | ${n(median(lens))} | ${n(mean(lens))} | ` +
        `${res.filter((r) => (r.snippet ?? "").includes(" … ")).length} |`,
    );
  }
  md.push("");
  md.push("`multi-passage` counts snippets containing the `\" … \"` join — the marker that");
  md.push("a snippet is non-contiguous and must not be quoted as one sentence.");
  md.push("");

  // ── Judged: snippet utility ──────────────────────────────────────────────
  if (judged.length > 0) {
    md.push("## Snippet utility (blind judge, 0-2)");
    md.push("");
    md.push("2 = carries a fact that answers the query · 1 = on-topic context only ·");
    md.push("0 = nav text, boilerplate, or fragments. The judge never sees which arm a");
    md.push("snippet came from. `unscored` counts absent snippets and judge errors and is");
    md.push("**not** folded into 0 — a gap is not the same finding as a useless excerpt.");
    md.push("");
    md.push("| arm | mean score | share scoring 2 | share scoring 0 | unscored | n |");
    md.push("|---|---:|---:|---:|---:|---:|");
    for (const arm of ARMS) {
      const all = judged.flatMap((j) => j.snippets.filter((s) => s.arm === arm));
      const scored = all.filter((s) => s.score !== null).map((s) => s.score as number);
      if (all.length === 0) continue;
      const pct = (k: number): string =>
        scored.length === 0 ? "—" : `${((scored.filter((s) => s === k).length / scored.length) * 100).toFixed(0)}%`;
      md.push(
        `| ${arm} | ${n(mean(scored), 2)} | ${pct(2)} | ${pct(0)} | ${all.length - scored.length} | ${scored.length} |`,
      );
    }
    md.push("");
    md.push("### By page shape");
    md.push("");
    md.push("Bucketed by the prior in `cases.ts`. The point of this table is the");
    md.push("`highlights-hostile` and `text-favoured` rows: a mean that only improves on");
    md.push("`highlights-favoured` cases is a narrower result than the headline suggests.");
    md.push("");
    md.push("| page shape | cases | text mean | highlights mean | Δ |");
    md.push("|---|---:|---:|---:|---:|");
    for (const shape of ["highlights-favoured", "text-favoured", "highlights-hostile", "neutral"] as const) {
      const inShape = judged.filter((j) => j.expect === shape);
      if (inShape.length === 0) continue;
      const m = (arm: Arm): number =>
        mean(
          inShape
            .flatMap((j) => j.snippets.filter((s) => s.arm === arm && s.score !== null))
            .map((s) => s.score as number),
        );
      const [t, h] = [m("text"), m("highlights")];
      md.push(
        `| ${shape} | ${inShape.length} | ${n(t, 2)} | ${n(h, 2)} | ` +
          `${Number.isNaN(t) || Number.isNaN(h) ? "—" : (h - t >= 0 ? "+" : "") + (h - t).toFixed(2)} |`,
      );
    }
    md.push("");

    // ── Judged: answer quality ─────────────────────────────────────────────
    md.push("## Answer quality (pairwise, both orders must agree)");
    md.push("");
    md.push("This is the arm upstream shipped no eval for. Each pair is judged twice with");
    md.push("the sides swapped; a winner counts only when both orders agree.");
    md.push("`no-consensus` means the verdict flipped with position — reported, not");
    md.push("resolved by picking one run.");
    md.push("");
    md.push("| verdict | cases |");
    md.push("|---|---:|");
    for (const v of ["highlights", "text", "tie", "no-consensus", "unscored"] as const) {
      md.push(`| ${v} | ${judged.filter((j) => j.answer_winner === v).length} |`);
    }
    md.push("");
    const decided = judged.filter(
      (j) => j.answer_winner === "highlights" || j.answer_winner === "text",
    );
    md.push(
      `Decided cases: ${decided.length}/${judged.length}. ` +
        (decided.length < 8
          ? "**Too few to call a direction** — this establishes a method and a null result, not a win."
          : "Read the split above against that denominator, not against the case count."),
    );
    md.push("");
    md.push("### Per case");
    md.push("");
    md.push("| case | shape | answer winner | note |");
    md.push("|---|---|---|---|");
    for (const j of judged) {
      md.push(`| \`${j.id}\` | ${j.expect} | ${j.answer_winner} | ${j.answer_note} |`);
    }
    md.push("");
  } else {
    md.push("## Judged sections");
    md.push("");
    md.push("Absent: `judge.ts` has not been run against this JSONL. Deterministic");
    md.push("metrics above stand on their own; snippet utility and answer quality need");
    md.push("the judge.");
    md.push("");
  }

  const outPath = join(HERE, "RESULTS.md");
  writeFileSync(outPath, `${md.join("\n")}\n`);
  console.log(`wrote ${outPath}`);
}

main();
