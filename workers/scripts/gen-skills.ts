import { createHash } from "node:crypto";
import { existsSync, readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";

import yaml from "js-yaml";

export interface SkillFrontmatter {
  name: string;
  description: string;
  [key: string]: unknown;
}

export interface SkillRecord {
  name: string;
  uri: string;
  text: string;
  frontmatter: SkillFrontmatter;
  digest: string;
  size: number;
  toolNames: string[];
}

const SKILL_FILE = "SKILL.md";
const FRONTMATTER_FENCE = /^---\n([\s\S]*?)\n---\n/;

function skillDirNames(skillsDir: string): string[] {
  return readdirSync(skillsDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && existsSync(join(skillsDir, entry.name, SKILL_FILE)))
    .map((entry) => entry.name)
    .sort();
}

/** Absolute paths of every `SKILL.md` under `skillsDir`, sorted by skill name. */
export function skillMarkdownPaths(skillsDir: string): string[] {
  return skillDirNames(skillsDir).map((dirName) => join(skillsDir, dirName, SKILL_FILE));
}

function parseFrontmatter(dirName: string, text: string): SkillFrontmatter {
  const block = FRONTMATTER_FENCE.exec(text)?.[1];
  if (block === undefined) {
    throw new Error(`skills/${dirName}/${SKILL_FILE}: no YAML frontmatter fence found`);
  }
  const parsed: unknown = yaml.load(block, { schema: yaml.CORE_SCHEMA });
  if (typeof parsed !== "object" || parsed === null || Array.isArray(parsed)) {
    throw new Error(`skills/${dirName}/${SKILL_FILE}: frontmatter is not a YAML mapping`);
  }
  const frontmatter = parsed as Record<string, unknown>;
  if (typeof frontmatter.name !== "string" || typeof frontmatter.description !== "string") {
    throw new Error(`skills/${dirName}/${SKILL_FILE}: frontmatter needs string name and description`);
  }
  if (frontmatter.name !== dirName) {
    throw new Error(
      `skills/${dirName}/${SKILL_FILE}: frontmatter name "${frontmatter.name}" differs from directory "${dirName}"`,
    );
  }
  return { ...frontmatter, name: frontmatter.name, description: frontmatter.description };
}

function namedTools(text: string, toolNames: readonly string[]): string[] {
  return toolNames
    .filter((toolName) => new RegExp(`(?<![A-Za-z0-9_])${toolName}(?![A-Za-z0-9_])`).test(text))
    .sort();
}

/** One record per skill directory under `skillsDir`, with the registered tools each skill names. */
export function readSkills(skillsDir: string, toolNames: readonly string[]): SkillRecord[] {
  return skillDirNames(skillsDir).map((dirName) => {
    const text = readFileSync(join(skillsDir, dirName, SKILL_FILE), "utf8");
    const frontmatter = parseFrontmatter(dirName, text);
    const named = namedTools(text, toolNames);
    if (named.length === 0) {
      throw new Error(`skills/${dirName}/${SKILL_FILE}: names no registered tool`);
    }
    return {
      name: dirName,
      uri: `skill://${dirName}/${SKILL_FILE}`,
      text,
      frontmatter,
      digest: `sha256:${createHash("sha256").update(text, "utf8").digest("hex")}`,
      size: Buffer.byteLength(text, "utf8"),
      toolNames: named,
    };
  });
}

/** The full source of `workers/src/generated/skills.ts`. */
export function renderSkillsModule(skills: readonly SkillRecord[]): string {
  return [
    "/**",
    " * GENERATED FILE — do not edit by hand.",
    " * Regenerated by `workers/scripts/gen-registry.ts` from `skills/`.",
    " */",
    "",
    "export type GeneratedSkill = {",
    "  readonly name: string;",
    "  readonly uri: string;",
    "  readonly text: string;",
    "  readonly frontmatter: {",
    "    readonly name: string;",
    "    readonly description: string;",
    "    readonly [key: string]: unknown;",
    "  };",
    "  readonly digest: string;",
    "  readonly size: number;",
    "  readonly toolNames: readonly string[];",
    "};",
    "",
    `export const SKILLS: readonly GeneratedSkill[] = ${JSON.stringify(skills, null, 2)};`,
    "",
  ].join("\n");
}
